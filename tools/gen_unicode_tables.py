"""Generate crates/docrs/src/unicode/tables.rs from the pinned Python oracle.

Run with the oracle interpreter (CPython 3.13, Unicode 15.1):
    .venv/bin/python tools/gen_unicode_tables.py

The tables pin Python's `str.casefold()` and `str.isspace()` (also used by
`re` `\\s` for str patterns) so the Rust port reproduces the oracle exactly
instead of relying on Rust's own Unicode helpers.
"""

import sys
import unicodedata

OUT = "crates/docrs/src/unicode/tables.rs"


def main() -> None:
    fold = []
    space = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = c.casefold()
        if f != c:
            fold.append((cp, f))
        if c.isspace():
            space.append(cp)
    lines = [
        "// @generated by tools/gen_unicode_tables.py — do not edit.",
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        f"pub const UNICODE_VERSION: &str = \"{unicodedata.unidata_version}\";",
        "",
        "/// Code points where Python `str.casefold()` differs from identity, sorted.",
        "pub static CASEFOLD: &[(u32, &str)] = &[",
    ]
    for cp, f in fold:
        escaped = "".join(f"\\u{{{ord(ch):X}}}" for ch in f)
        lines.append(f"    (0x{cp:X}, \"{escaped}\"),")
    lines.append("];")
    lines.append("")
    lines.append("/// Code points where Python `str.isspace()` is true, sorted.")
    lines.append("pub static ISSPACE: &[u32] = &[")
    for cp in space:
        lines.append(f"    0x{cp:X},")
    lines.append("];")
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"casefold entries: {len(fold)}, isspace entries: {len(space)}")


if __name__ == "__main__":
    main()

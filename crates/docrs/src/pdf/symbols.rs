//! What the characters of symbol fonts stand for, and which of them the
//! converter writes itself.

/// The character `ch`, set in `family`, stands for: Symbol and Wingdings
/// codes (U+0020-00FF, or U+F020-F0FF) through their tables, any other
/// character as itself; `None` for a code of another symbol font, a
/// private-use code of a text font, or a table without an entry.
pub(super) fn meaning(family: &str, ch: char) -> Option<char> {
    let code = ch as u32;
    let low = match code {
        0x20..=0xFF => code,
        0xF020..=0xF0FF => code & 0xFF,
        _ => return Some(ch),
    };
    let at = (low - 0x20) as usize;
    let mapped = match family.trim().to_lowercase().as_str() {
        "symbol" => u32::from(SYMBOL[at]),
        "wingdings" => WINGDINGS[at],
        "wingdings 2" | "wingdings 3" | "webdings" => 0,
        _ if code <= 0xFF => code,
        _ => 0,
    };
    char::from_u32(mapped).filter(|_| mapped != 0)
}


#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn symbol_fonts_stand_for_their_unicode_characters() {
        let cases = [
            ("Symbol", '\u{F0B7}', '\u{2022}'),
            ("Symbol", '\u{B7}', '\u{2022}'),
            ("Symbol", 'a', 'α'),
            ("Symbol", '\u{F044}', 'Δ'),
            ("Symbol", '\u{2022}', '\u{2022}'),
            ("Wingdings", '\u{F0A7}', '\u{25AA}'),
            ("Wingdings", '\u{F0FC}', '\u{2714}'),
            ("Wingdings", '\u{F0D8}', '\u{2B9A}'),
            ("wingdings", 'Q', '\u{2708}'),
            ("MS Gothic", '\u{2610}', '\u{2610}'),
            ("MS Gothic", 'A', 'A'),
        ];
        for (family, ch, meaning_of) in cases {
            assert_eq!(meaning(family, ch), Some(meaning_of), "{family} {ch:?}");
        }
        assert_eq!(meaning("Wingdings", '\u{F0FF}'), None);
        assert_eq!(meaning("Webdings", '\u{F021}'), None);
        assert_eq!(meaning("Courier New", 'o'), Some('o'));
        assert_eq!(meaning("Courier New", '\u{F06F}'), None);
    }
}
